            <h1>About District</h1><div id="post-1532" class="post-1532 page type-page status-publish hentry">
		<p>(Hindi: सिद्धार्थनगर , Urdu: سدھارتھ نگر ‎) is one of the 75 districts of Uttar Pradesh state in Northern India. Naugarh town is the district headquarters. Naugarh is also a Railway Station on Gorakhpur-Anandnagar-Gonda broad-gauge line. Siddharth Nagar district is a part of Basti division. The district is known for the ruins of the Shakya Janapada, at Piprahwa which is 22 km away from the district headquarters Naugarh.</p>
<p>The district was named after prince Siddhartha, the pre-enlightenment name of Buddha, as he spent his early years (till the age of 29 years) in Kapilavastu, parts of which included territory in this district.Siddharthnagar District lies between 27°N to 27°28’N and 82°45’E to 83°10’E. The district borders Nepal’s district Kapilvastu on the north and Rupandehi on the northeast. Otherwise it is surrounded by other districts of Uttar Pradesh: Maharajganj on the east, Basti and Sant Kabir Nagar on the south, and Balrampur on the west. Siddarthnagar’s area is 2,895 km sqaure.</p>
<p>Siddharthnagar district comprises 5 tehsils;</p>
<ol>
<li>Naugarh (Sadar Tehsil)</li>
<li>Shohratgarh</li>
<li>Bansi</li>
<li>Itwa</li>
<li>Domariyaganj.</li>
</ol>
<p>There are five Vidhan Sabha constituencies in the district. These are Shohratgarh, Kapilvastu, Bansi, Itwa and Domariyaganj. The only Lok Sabha constituency in this district is Domariyaganj.</p>
<p>According to the census 2011 Siddharthnagar district has a population of 25,59,297. The district has a population density of 884 inhabitants per square kilometre. Its population growth rate over the decade 2001-2011 was 25.4%. Siddharth Nagar has a sex ratio of 976 females for every 1000 males, and a literacy rate of 59.2.</p>
<h2>University<strong>:</strong></h2>
<p>Siddharth University is a state university in Kapilvastu, Siddharthnagar, Uttar Pradesh.</p>

